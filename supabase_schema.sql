CREATE TABLE IF NOT EXISTS students (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_no varchar(50) NOT NULL UNIQUE,
    first_name varchar(100) NOT NULL,
    last_name varchar(100) NOT NULL,
    middle_name varchar(100),
    course varchar(100),
    year_level varchar(20),
    section varchar(50),
    email varchar(150),
    contact_number varchar(40),
    qr_code varchar(255) UNIQUE,
    account_status varchar(8) NOT NULL DEFAULT 'ACTIVE' CHECK (account_status IN ('ACTIVE', 'INACTIVE')),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS events (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name varchar(180) NOT NULL,
    description text,
    event_type varchar(80),
    venue varchar(180),
    event_date date NOT NULL,
    start_time time NOT NULL,
    end_time time NOT NULL,
    scan_in_start time NOT NULL,
    scan_in_end time NOT NULL,
    scan_out_start time NOT NULL,
    scan_out_end time NOT NULL,
    fine_amount numeric(10, 2) NOT NULL DEFAULT 0,
    attendance_required smallint NOT NULL DEFAULT 1 CHECK (attendance_required IN (0, 1)),
    status varchar(10) NOT NULL DEFAULT 'UPCOMING'
        CHECK (status IN ('UPCOMING', 'ACTIVE', 'COMPLETED', 'CANCELLED', 'DRAFT', 'CLOSED')),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_events_active ON events (status, event_date);

CREATE TABLE IF NOT EXISTS event_students (
    event_id integer NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    PRIMARY KEY (event_id, student_id)
);

CREATE TABLE IF NOT EXISTS event_attendance (
    attendance_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    event_id integer NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    scan_in timestamp,
    scan_out timestamp,
    attendance_status varchar(10) NOT NULL DEFAULT 'INCOMPLETE'
        CHECK (attendance_status IN ('PRESENT', 'ABSENT', 'LATE', 'EXCUSED', 'INCOMPLETE')),
    scanner varchar(80),
    recorded_date date NOT NULL,
    remarks varchar(255),
    UNIQUE (event_id, student_id)
);

CREATE TABLE IF NOT EXISTS fines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id integer NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    amount numeric(10, 2) NOT NULL,
    reason varchar(255) NOT NULL,
    status varchar(15) NOT NULL DEFAULT 'UNPAID'
        CHECK (status IN ('UNPAID', 'PARTIALLY PAID', 'PAID', 'WAIVED')),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (event_id, student_id)
);

CREATE TABLE IF NOT EXISTS payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fine_id bigint NOT NULL REFERENCES fines(id) ON DELETE CASCADE,
    amount numeric(10, 2) NOT NULL,
    payment_method varchar(20) NOT NULL DEFAULT 'CASH'
        CHECK (payment_method IN ('CASH', 'GCASH', 'MAYA', 'BANK TRANSFER', 'OTHER')),
    reference_number varchar(100),
    remarks varchar(255),
    paid_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recorded_by integer
);

CREATE TABLE IF NOT EXISTS clearance (
    student_id integer PRIMARY KEY REFERENCES students(id) ON DELETE CASCADE,
    status varchar(10) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'ELIGIBLE', 'ON HOLD', 'SIGNED')),
    signed_at timestamp,
    signed_by integer
);

CREATE TABLE IF NOT EXISTS ssc_users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name varchar(150) NOT NULL,
    username varchar(80) NOT NULL UNIQUE,
    email varchar(150) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    must_change_password smallint NOT NULL DEFAULT 1 CHECK (must_change_password IN (0, 1)),
    permissions json,
    account_status varchar(8) NOT NULL DEFAULT 'ACTIVE' CHECK (account_status IN ('ACTIVE', 'INACTIVE')),
    last_login timestamp,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS admin_users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name varchar(150) NOT NULL,
    email varchar(150) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    account_status varchar(8) NOT NULL DEFAULT 'ACTIVE' CHECK (account_status IN ('ACTIVE', 'INACTIVE')),
    last_login timestamp,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS event_requests (
    event_request_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ssc_user_id integer NOT NULL REFERENCES ssc_users(id) ON DELETE CASCADE,
    event_name varchar(180) NOT NULL,
    description text,
    event_type varchar(80),
    venue varchar(180),
    event_date date NOT NULL,
    start_time time NOT NULL,
    end_time time NOT NULL,
    scan_in_start time NOT NULL,
    scan_in_end time NOT NULL,
    scan_out_start time NOT NULL,
    scan_out_end time NOT NULL,
    fine_amount numeric(10, 2) NOT NULL DEFAULT 0,
    status varchar(8) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    admin_note varchar(255),
    reviewed_by integer,
    reviewed_at timestamp,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_event_requests_status ON event_requests (status);

CREATE TABLE IF NOT EXISTS activity_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_type varchar(6) NOT NULL DEFAULT 'ADMIN' CHECK (actor_type IN ('ADMIN', 'SSC', 'SYSTEM')),
    actor_id integer,
    action varchar(100) NOT NULL,
    entity_type varchar(80),
    entity_id bigint,
    details text,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_activity_logs_created ON activity_logs (created_at);

CREATE TABLE IF NOT EXISTS notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_type varchar(80) NOT NULL,
    message varchar(255) NOT NULL,
    is_read smallint NOT NULL DEFAULT 0 CHECK (is_read IN (0, 1)),
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ssc_settings (
    setting_key varchar(80) PRIMARY KEY,
    setting_value text NOT NULL,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS app_sessions (
    session_id varchar(128) PRIMARY KEY,
    session_data text NOT NULL,
    last_activity bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_app_sessions_last_activity ON app_sessions (last_activity);

CREATE TABLE IF NOT EXISTS attendance_corrections (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_id bigint NOT NULL REFERENCES event_attendance(attendance_id) ON DELETE CASCADE,
    old_status varchar(30) NOT NULL,
    new_status varchar(30) NOT NULL,
    reason varchar(255) NOT NULL,
    corrected_by integer NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS school_announcements (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(160) NOT NULL,
    message text NOT NULL,
    announcement_type varchar(40) NOT NULL DEFAULT 'ANNOUNCEMENT',
    status varchar(8) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    priority smallint NOT NULL DEFAULT 5,
    sort_order integer NOT NULL DEFAULT 0,
    starts_at timestamp,
    ends_at timestamp,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_school_announcements_active
    ON school_announcements (status, starts_at, ends_at, priority, sort_order);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS students_set_updated_at ON students;
CREATE TRIGGER students_set_updated_at BEFORE UPDATE ON students
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS ssc_settings_set_updated_at ON ssc_settings;
CREATE TRIGGER ssc_settings_set_updated_at BEFORE UPDATE ON ssc_settings
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
DROP TRIGGER IF EXISTS school_announcements_set_updated_at ON school_announcements;
CREATE TRIGGER school_announcements_set_updated_at BEFORE UPDATE ON school_announcements
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

